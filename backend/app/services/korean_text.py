"""한국어를 BM25에 태우기 위한 최소한의 손질.

형태소 분석기(mecab, kiwi)를 쓰지 않습니다. 이유가 둘입니다. 하나는 사전
파일이 수십 MB라 Render 무료 등급에 부담이 된다는 것이고, 다른 하나는 설치가
플랫폼을 탄다는 것입니다. 배포일이 정해져 있는데 빌드에서 막히면 되돌릴
시간이 없습니다.

대신 조사만 떼어 냅니다. "운영자금이", "운영자금을", "운영자금은"이 서로
다른 낱말로 세어지는 것만 막아도 BM25는 제 몫을 합니다. 완벽한 분석이
목적이 아니라 같은 말을 같게 세는 것이 목적입니다.

의미가 먼 표현("장사가 안돼요" ↔ "경영안정자금")은 여기서 못 잡습니다.
그쪽은 임베딩 검색이 맡습니다. 둘을 섞는 이유입니다.
"""
from __future__ import annotations

import re

# 낱말 단위로 자릅니다. 한글·영문·숫자만 남기고 나머지는 경계로 봅니다.
_TOKEN = re.compile(r"[가-힣]+|[A-Za-z]+|\d+")

# 긴 것부터 봅니다. "에서"를 "서"보다 먼저 떼야 합니다.
_JOSA = (
    "으로부터", "로부터", "에서는", "에게서", "이라고", "라고는",
    "에서", "에게", "으로", "이나", "라도", "부터", "까지", "처럼", "보다", "마다",
    "이는", "가는", "은는",
    "은", "는", "이", "가", "을", "를", "에", "의", "로", "와", "과", "도", "만", "랑", "나",
)

# 이대로 두면 거의 모든 공고에 걸려 변별력이 없습니다.
#
# IDF가 알아서 눌러 줄 것이라 여기고 처음에는 낱개 낱말만 넣었습니다. 그런데
# "지원사업"처럼 **붙어 있는 복합어**는 한 낱말로 잘려 그물을 빠져나갔습니다.
# "스마트기기나 키오스크 들여놓는 지원사업"으로 물었더니 BM25 상위 여섯 개가
# 전부 '지원사업' 하나만 걸린 것들이었고, 점수도 0.74~0.76으로 붙어 있어
# 사실상 제비뽑기였습니다. 그 잡음이 순위 섞기로 그대로 들어옵니다.
_STOP = {
    "지원", "사업", "공고", "모집", "안내", "신청", "관련", "대상", "경우", "이내",
    "또는", "및", "등", "제", "년", "월", "일", "차", "회", "개", "내", "위",
    "있습니다", "합니다", "됩니다", "하는", "있는", "되는", "위한", "따른", "대한",
    # 복합어로 붙어 다니는 것들
    "지원사업", "모집공고", "사업공고", "지원계획", "모집안내", "참여기업",
    "참가기업", "신청안내", "지원공고", "선정계획", "추가모집", "지원금",
    "사업자", "기업", "업체", "참여", "참가", "선정", "운영", "추진",
}


def _strip_josa(word: str) -> str:
    """조사를 뗍니다. 뗀 뒤가 두 글자 미만이면 원형을 지킵니다.

    "이자"에서 "이"를 떼면 "자"가 남아 뜻이 사라집니다. 짧은 낱말을
    건드리지 않는 것만으로 이런 사고가 대부분 막힙니다.
    """
    if len(word) < 3:
        return word
    for j in _JOSA:
        if word.endswith(j) and len(word) - len(j) >= 2:
            return word[: -len(j)]
    return word


def tokenize(text: str) -> list[str]:
    """검색어와 문서를 같은 방식으로 자릅니다. 양쪽이 어긋나면 안 됩니다."""
    out = []
    for raw in _TOKEN.findall(text or ""):
        w = raw.lower() if raw.isascii() else raw
        if w.isdigit():
            continue                      # 숫자 단독은 잡음입니다. 금액은 따로 다룹니다.
        if len(w) < 2:
            continue
        w = _strip_josa(w)
        if w in _STOP or len(w) < 2:
            continue
        out.append(w)
    return out
